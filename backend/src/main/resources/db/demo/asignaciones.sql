MERGE INTO SGR_USUARIO_PERFIL t
USING (
    SELECT u.ID USUARIO, p.ID PERFIL, ? ALCANCE, c.ID CENTRO, ? VEHICULO,
           (SELECT ID FROM SGR_USUARIO WHERE CODIGO = 'SIGREC_TECNICO') ACTOR
    FROM SGR_USUARIO u
    CROSS JOIN SGR_PERFIL p
    LEFT JOIN SGR_CENTRO c ON c.CODIGO = ?
    WHERE u.CODIGO = ? AND p.CODIGO = ?
) d
ON (t.ID_USUARIO = d.USUARIO AND t.ID_PERFIL = d.PERFIL AND t.ALCANCE = d.ALCANCE
    AND (t.ID_CENTRO = d.CENTRO OR (t.ID_CENTRO IS NULL AND d.CENTRO IS NULL))
    AND (t.CODIGO_VEHICULO = d.VEHICULO OR (t.CODIGO_VEHICULO IS NULL AND d.VEHICULO IS NULL)))
WHEN NOT MATCHED THEN INSERT (ID_USUARIO, ID_PERFIL, ALCANCE, ID_CENTRO, CODIGO_VEHICULO,
                              ESTADO, ELIMINADO, USU_REGISTRA, FEC_REGISTRA)
VALUES (d.USUARIO, d.PERFIL, d.ALCANCE, d.CENTRO, d.VEHICULO, 1, 0, d.ACTOR, SYSDATE)
