-- SPEC 037. Las contraseñas BCrypt se reciben como parámetros del proceso.
MERGE INTO SGR_USUARIO u
USING (SELECT ? CODIGO, ? NOMBRE, ? PASSWORD_HASH,
             (SELECT ID FROM SGR_USUARIO WHERE CODIGO = 'SIGREC_TECNICO') ACTOR FROM DUAL) d
ON (u.CODIGO = d.CODIGO)
WHEN NOT MATCHED THEN INSERT (CODIGO, NOMBRE, TIPO, PROVEEDOR_IDENTIDAD, SUJETO_IDENTIDAD,
                              PASSWORD_HASH, ESTADO, ELIMINADO, USU_REGISTRA, FEC_REGISTRA)
VALUES (d.CODIGO, d.NOMBRE, 'HUMANO', 'LOCAL', d.CODIGO, d.PASSWORD_HASH, 1, 0, d.ACTOR, SYSDATE)
