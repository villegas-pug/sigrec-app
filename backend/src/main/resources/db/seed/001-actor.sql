-- SPEC 037. Arranque del actor técnico según SEG-04 en una sola transacción.
BEGIN
    EXECUTE IMMEDIATE 'SET CONSTRAINTS SGR_FK_USUARIO_REG DEFERRED';
    MERGE INTO SGR_USUARIO u
    USING (SELECT 'SIGREC_TECNICO' CODIGO FROM DUAL) d
    ON (u.CODIGO = d.CODIGO)
    WHEN NOT MATCHED THEN INSERT (CODIGO, NOMBRE, TIPO, ESTADO, ELIMINADO, USU_REGISTRA, FEC_REGISTRA)
        VALUES (d.CODIGO, 'Importación SIGREC', 'TECNICO', 1, 0, 0, SYSDATE);
    UPDATE SGR_USUARIO SET USU_REGISTRA = ID WHERE CODIGO = 'SIGREC_TECNICO' AND USU_REGISTRA = 0;
    EXECUTE IMMEDIATE 'SET CONSTRAINTS SGR_FK_USUARIO_REG IMMEDIATE';
END;
