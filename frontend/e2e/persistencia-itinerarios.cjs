// Flujo integrado de itinerario ejecutado y consumo declarado (API Oracle real).
const assert = require('node:assert/strict')

async function crearItinerarioIntegrado (page, base, api, guardarFase, registro, vehiculo) {
  const itinerario = { ...registro.itinerario, vehiculoId: vehiculo.id }
  const consumo = { ...registro.consumo, vehiculoId: vehiculo.id }
  guardarFase('itinerario-reservado', 'itinerario', { vehiculoId: vehiculo.id })

  await page.goto(`${base}#/movilidad/itinerarios?vehiculo=${encodeURIComponent(vehiculo.id)}`)
  await page.getByRole('button', { name: 'Registrar itinerario' }).waitFor({ timeout: 60000 })
  await page.getByRole('button', { name: 'Registrar itinerario' }).click()
  const alta = page.locator('.q-dialog:visible').filter({ has: page.getByRole('heading', { name: 'Registrar itinerario' }) })
  const fecha = alta.getByLabel('Fecha *')
  const proposito = alta.getByLabel('Propósito *')
  const destinos = alta.getByLabel('Destinos, separados por comas *')
  await fecha.fill('')
  await proposito.fill('')
  await destinos.fill('')
  await alta.getByRole('button', { name: 'Guardar', exact: true }).click()
  for (const campo of [fecha, proposito, destinos]) {
    await campo.locator('xpath=ancestor::label[contains(@class,"q-field")]').getByText('Campo obligatorio').waitFor()
  }

  await fecha.fill(`${new Date().getFullYear() + 1}-01-01`)
  await proposito.fill(itinerario.proposito)
  await destinos.fill(itinerario.destino)
  await alta.getByRole('checkbox', { name: 'El recorrido ya se realizó' }).check()
  await alta.getByRole('button', { name: 'Guardar', exact: true }).click()
  await alta.getByText('No puede ser posterior a hoy').waitFor()
  await alta.getByRole('checkbox', { name: 'El recorrido ya se realizó' }).uncheck()
  await fecha.fill(itinerario.fecha)
  await alta.getByLabel('Salida').fill('15:00')
  await alta.getByLabel('Llegada').fill('14:00')
  await alta.getByRole('button', { name: 'Guardar', exact: true }).click()
  await alta.getByText('La llegada no puede ser anterior a la salida', { exact: true }).waitFor()
  await alta.getByLabel('Salida').fill(itinerario.salidaPrevista)
  await alta.getByLabel('Llegada').fill(itinerario.llegadaPrevista)
  await alta.getByLabel('Distancia (km)').fill(String(itinerario.kmPrevistos))
  await alta.getByRole('button', { name: 'Guardar', exact: true }).click()
  await alta.waitFor({ state: 'hidden', timeout: 30000 })

  const altas = await api(page, 'GET', 'itinerarios')
  assert.equal(altas.status, 200, 'No se pudo consultar la API de itinerarios')
  const creado = altas.json?.data?.find(item => item.vehiculoId === vehiculo.id && item.proposito === itinerario.proposito)
  assert.ok(creado, 'El itinerario creado desde Vue no aparece en Oracle')
  assert.deepEqual(creado.destinos, [itinerario.destino])
  assert.equal(Number(creado.previsto?.km), itinerario.kmPrevistos)
  guardarFase('itinerario-creado', 'itinerario', { ...itinerario, id: creado.id })

  await page.getByRole('button', { name: `Acciones del itinerario ${creado.id}` }).click()
  await page.getByText('Actualizar itinerario', { exact: true }).click()
  const edicion = page.locator('.q-dialog:visible').filter({ has: page.getByRole('heading', { name: 'Actualizar itinerario' }) })
  await edicion.getByLabel('Propósito *').fill(itinerario.propositoEditado)
  guardarFase('itinerario-editando', 'itinerario', { ...itinerario, id: creado.id })
  await edicion.getByRole('button', { name: 'Guardar', exact: true }).click()
  await edicion.waitFor({ state: 'hidden', timeout: 30000 })
  const editados = await api(page, 'GET', 'itinerarios')
  assert.equal(editados.json?.data?.find(item => item.id === creado.id)?.proposito, itinerario.propositoEditado)
  guardarFase('itinerario-editado', 'itinerario', { ...itinerario, id: creado.id })

  await page.getByRole('button', { name: 'Informar ejecución', exact: true }).first().click()
  const ejecucion = page.locator('.q-dialog:visible').filter({ has: page.getByRole('heading', { name: 'Informar ejecución' }) })
  await ejecucion.getByLabel('Salida').fill('10:00')
  await ejecucion.getByLabel('Llegada').fill('09:00')
  await ejecucion.getByRole('button', { name: 'Guardar', exact: true }).click()
  await ejecucion.getByText('La llegada no puede ser anterior a la salida', { exact: true }).waitFor()
  await ejecucion.getByLabel('Salida').fill(itinerario.salidaReal)
  await ejecucion.getByLabel('Llegada').fill(itinerario.llegadaReal)
  await ejecucion.getByLabel('Distancia (km)').fill(String(itinerario.kmRealizados))
  guardarFase('itinerario-ejecutando', 'itinerario', { ...itinerario, id: creado.id })
  const respuestaEjecucion = page.waitForResponse(
    respuesta => new URL(respuesta.url()).pathname.endsWith(`/itinerarios/${encodeURIComponent(creado.id)}/ejecucion`),
    { timeout: 20000 }
  ).catch(() => null)
  await ejecucion.getByRole('button', { name: 'Guardar', exact: true }).click()
  const respuesta = await respuestaEjecucion
  if (!respuesta) {
    const errores = await ejecucion.locator('.q-field--error').allInnerTexts().catch(() => [])
    const avisos = await page.locator('.q-notification').allInnerTexts().catch(() => [])
    const campos = await ejecucion.locator('input').evaluateAll(inputs => inputs.map(input => ({
      type: input.type,
      value: input.value,
      valid: input.checkValidity(),
      validationMessage: input.validationMessage
    }))).catch(() => [])
    const enviarDeshabilitado = await ejecucion.getByRole('button', { name: 'Guardar', exact: true }).isDisabled().catch(() => null)
    const dialogo = (await ejecucion.innerText().catch(() => 'sin detalle visible')).replace(/\s+/g, ' ').slice(-500)
    throw new Error(`No se envió la ejecución del itinerario ${creado.id}; errores=${JSON.stringify(errores)}; avisos=${JSON.stringify(avisos)}; campos=${JSON.stringify(campos)}; enviarDeshabilitado=${enviarDeshabilitado}; diálogo=${dialogo}`)
  }
  const resultadoEjecucion = await respuesta.json().catch(() => null)
  assert.equal(
    respuesta.status(),
    200,
    `La API rechazó la ejecución del itinerario (${respuesta.status()}): ${resultadoEjecucion?.message || 'sin detalle'}`
  )
  await ejecucion.waitFor({ state: 'hidden', timeout: 30000 })
  const ejecutados = await api(page, 'GET', 'itinerarios')
  const ejecutado = ejecutados.json?.data?.find(item => item.id === creado.id)
  assert.equal(ejecutado?.realizado?.salida, itinerario.salidaReal)
  assert.equal(ejecutado?.realizado?.llegada, itinerario.llegadaReal)
  assert.equal(Number(ejecutado?.realizado?.km), itinerario.kmRealizados)
  guardarFase('itinerario-ejecutado', 'itinerario', { ...itinerario, id: creado.id })

  await page.getByRole('button', { name: 'Declarar consumo', exact: true }).first().click()
  const altaConsumo = page.locator('.q-dialog:visible').filter({ has: page.getByRole('heading', { name: 'Informar combustible' }) })
  await altaConsumo.getByLabel('Recorrido *').waitFor()
  await altaConsumo.getByText(creado.id, { exact: false }).waitFor()
  const fechaConsumo = altaConsumo.getByLabel('Fecha *')
  const cantidad = altaConsumo.getByLabel('Cantidad *')
  await fechaConsumo.fill('')
  await cantidad.fill('')
  await altaConsumo.getByRole('button', { name: 'Registrar', exact: true }).click()
  await fechaConsumo.locator('xpath=ancestor::label[contains(@class,"q-field")]').getByText('Campo obligatorio').waitFor()
  await cantidad.locator('xpath=ancestor::label[contains(@class,"q-field")]').getByText('Indique un valor mayor que cero').waitFor()
  await fechaConsumo.fill(`${new Date().getFullYear() + 1}-01-01`)
  await cantidad.fill('-1')
  await altaConsumo.getByRole('button', { name: 'Registrar', exact: true }).click()
  await altaConsumo.getByText('No puede ser posterior a hoy').waitFor()
  await altaConsumo.getByText('Indique un valor mayor que cero', { exact: true }).waitFor()
  await fechaConsumo.fill(consumo.fecha)
  await cantidad.fill(String(consumo.cantidad))
  await altaConsumo.getByLabel('Sustento (vale, declaración…)').fill(consumo.sustento)
  guardarFase('consumo-reservado', 'consumo', { ...consumo, itinerarioId: creado.id })
  await altaConsumo.getByRole('button', { name: 'Registrar', exact: true }).click()
  await altaConsumo.waitFor({ state: 'hidden', timeout: 30000 })
  const registrosAlta = await api(page, 'GET', 'combustible')
  assert.equal(registrosAlta.status, 200)
  const consumoCreado = registrosAlta.json?.data?.find(item => item.itinerarioId === creado.id && item.sustento === consumo.sustento)
  assert.ok(consumoCreado, 'El consumo del recorrido no aparece en Oracle')
  assert.equal(consumoCreado.tipo, 'consumo')
  assert.equal(Number(consumoCreado.cantidad), consumo.cantidad)
  guardarFase('consumo-creado', 'consumo', { ...consumo, itinerarioId: creado.id, id: consumoCreado.id })

  await page.goto(`${base}#/movilidad/combustible?vehiculo=${encodeURIComponent(vehiculo.id)}`)
  await page.getByText(consumo.sustento, { exact: true }).waitFor({ timeout: 60000 })
  await page.getByRole('button', { name: `Acciones del registro ${consumoCreado.id}` }).click()
  await page.getByText('Actualizar registro', { exact: true }).click()
  const edicionConsumo = page.locator('.q-dialog:visible').filter({ has: page.getByRole('heading', { name: 'Actualizar registro de combustible' }) })
  await edicionConsumo.getByLabel('Cantidad *').fill(String(consumo.cantidadEditada))
  await edicionConsumo.getByLabel('Sustento (vale, declaración…)').fill(consumo.sustentoEditado)
  guardarFase('consumo-editando', 'consumo', { ...consumo, itinerarioId: creado.id, id: consumoCreado.id })
  await edicionConsumo.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await edicionConsumo.waitFor({ state: 'hidden', timeout: 30000 })
  const consumosEditados = await api(page, 'GET', 'combustible')
  const consumoEditado = consumosEditados.json?.data?.find(item => item.id === consumoCreado.id)
  assert.equal(consumoEditado?.sustento, consumo.sustentoEditado)
  assert.equal(Number(consumoEditado?.cantidad), consumo.cantidadEditada)
  guardarFase('consumo-editado', 'consumo', { ...consumo, itinerarioId: creado.id, id: consumoCreado.id })

  await page.goto(`${base}#/movilidad/itinerarios?vehiculo=${encodeURIComponent(vehiculo.id)}`)
  await page.getByRole('button', { name: `Acciones del itinerario ${creado.id}` }).click()
  await page.getByText('Anular itinerario', { exact: true }).click()
  const bloqueo = page.locator('.q-dialog:visible').filter({ has: page.getByRole('heading', { name: 'Anular itinerario' }) })
  await bloqueo.getByText('No se puede anular todavía.').waitFor()
  await bloqueo.getByText(consumoCreado.id, { exact: false }).waitFor()
  assert.equal(await bloqueo.getByRole('button', { name: 'Anular', exact: true }).isDisabled(), true)
  await bloqueo.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await bloqueo.waitFor({ state: 'hidden' })
  assert.equal((await api(page, 'GET', 'itinerarios')).json?.data?.find(item => item.id === creado.id)?.anulacion ?? null, null)

  await page.goto(`${base}#/movilidad/combustible?vehiculo=${encodeURIComponent(vehiculo.id)}`)
  await page.getByRole('button', { name: `Acciones del registro ${consumoCreado.id}` }).click()
  await page.getByText('Anular registro', { exact: true }).click()
  const anulacionConsumo = page.locator('.q-dialog:visible').filter({ has: page.getByRole('heading', { name: 'Anular registro de combustible' }) })
  await anulacionConsumo.getByRole('button', { name: 'Anular', exact: true }).click()
  await anulacionConsumo.getByLabel('Motivo *').locator('xpath=ancestor::label[contains(@class,"q-field")]').getByText('Campo obligatorio').waitFor()
  await anulacionConsumo.getByLabel('Motivo *').fill('E2E: anulación lógica del consumo')
  guardarFase('consumo-anulando', 'consumo', { ...consumo, itinerarioId: creado.id, id: consumoCreado.id })
  await anulacionConsumo.getByRole('button', { name: 'Anular', exact: true }).click()
  await anulacionConsumo.waitFor({ state: 'hidden', timeout: 30000 })
  assert.ok((await api(page, 'GET', 'combustible')).json?.data?.find(item => item.id === consumoCreado.id)?.anulacion)
  guardarFase('consumo-anulado', 'consumo', { ...consumo, itinerarioId: creado.id, id: consumoCreado.id })

  await page.goto(`${base}#/movilidad/itinerarios?vehiculo=${encodeURIComponent(vehiculo.id)}`)
  await page.getByRole('button', { name: `Acciones del itinerario ${creado.id}` }).click()
  await page.getByText('Anular itinerario', { exact: true }).click()
  const anulacionItinerario = page.locator('.q-dialog:visible').filter({ has: page.getByRole('heading', { name: 'Anular itinerario' }) })
  await anulacionItinerario.getByRole('button', { name: 'Anular', exact: true }).click()
  await anulacionItinerario.getByLabel('Motivo *').locator('xpath=ancestor::label[contains(@class,"q-field")]').getByText('Campo obligatorio').waitFor()
  await anulacionItinerario.getByLabel('Motivo *').fill('E2E: anulación lógica del itinerario')
  guardarFase('itinerario-anulando', 'itinerario', { ...itinerario, id: creado.id })
  await anulacionItinerario.getByRole('button', { name: 'Anular', exact: true }).click()
  await anulacionItinerario.waitFor({ state: 'hidden', timeout: 30000 })
  assert.ok((await api(page, 'GET', 'itinerarios')).json?.data?.find(item => item.id === creado.id)?.anulacion)
  guardarFase('itinerario-anulado', 'itinerario', { ...itinerario, id: creado.id })

  await page.getByText('Mostrar inactivos', { exact: true }).click()
  await page.getByRole('button', { name: `Acciones del itinerario ${creado.id}` }).click()
  await page.getByText('Reactivar itinerario', { exact: true }).click()
  await page.getByRole('button', { name: 'Reactivar', exact: true }).click()
  await page.getByText('Itinerario reactivado.', { exact: true }).waitFor()
  assert.equal((await api(page, 'GET', 'itinerarios')).json?.data?.find(item => item.id === creado.id)?.anulacion ?? null, null)
  guardarFase('itinerario-reactivado', 'itinerario', { ...itinerario, id: creado.id })

  await page.goto(`${base}#/movilidad/combustible?vehiculo=${encodeURIComponent(vehiculo.id)}`)
  await page.getByText('Mostrar inactivos', { exact: true }).click()
  await page.getByRole('button', { name: `Acciones del registro ${consumoCreado.id}` }).click()
  await page.getByText('Reactivar registro', { exact: true }).click()
  await page.getByRole('button', { name: 'Reactivar', exact: true }).click()
  await page.getByText('Registro de combustible reactivado.', { exact: true }).waitFor()
  assert.equal((await api(page, 'GET', 'combustible')).json?.data?.find(item => item.id === consumoCreado.id)?.anulacion ?? null, null)
  guardarFase('consumo-reactivado', 'consumo', { ...consumo, itinerarioId: creado.id, id: consumoCreado.id })
}

module.exports = { crearItinerarioIntegrado }
